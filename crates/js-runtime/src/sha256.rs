//! M96.7: 自研 SHA-256（FIPS 180-4）——`crypto.subtle.digest` 的 Rust 原生后端。
//!
//! 动机（实弹铁证）：xcancel cap PoW 的 JS fallback solver 在 QuickJS worker
//! 里用纯 JS SHA-256 循环解题，实测 0.055ms/hash，30 题 ≈ 4.8s；Chrome
//! wasm 路径 ≈ 0.1s——challenge→verify 时差是 50 倍级族群信号。
//! 本模块手写实现（自研原则 G2，不引 sha2 crate），预期单次 <5μs。
//!
//! 正确性基准：NIST 标准测试向量（空串/abc/长串）入库单测。

